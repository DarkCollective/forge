/*
 * The names of the common object identifiers (algorithms, X.500 attribute types, X.509 extensions, key
 * purposes, elliptic curves). The table is data for the `asn1:oid-name`, `asn1:oid-short` and
 * `asn1:oid-find` primitives (src/prims/asn1.ts); it lives here, not in prims/, because every file in
 * prims/ is loaded as a vocabulary's primitive module.
 *
 * Why a table in TypeScript and not in FL: FL has no per-vocabulary constants, so an FL table is rebuilt
 * on every call (measured at the time of writing: a record of 200 pairs costs about 1,800 VM steps to
 * build, on every lookup). The primitive builds its maps once.
 *
 * The names are OpenSSL's short or long names (so `openssl asn1parse` and the tools built on it agree).
 * Every entry was checked while writing the table: `openssl asn1parse -genstr OID:<name>` and
 * `OID:<dotted>` give the same bytes. Three names are not OpenSSL's and were not checked that way:
 * certificateTemplateName and certificateTemplate (the Microsoft certificate template extensions,
 * MS-WCCE 2.2.2.7) and extensionRequest (the PKCS #9 name of 1.2.840.113549.1.9.14, which OpenSSL calls
 * "Extension Request"). src/asn1.test.ts pins a sample. The third element is the abbreviation printed in
 * a distinguished name (CN, O, OU, C, ...), for attribute types only.
 */

