const { bytes, str, bool } = valueHelpers;
const bundle = await loadBundleNode(["yara"]);
const runtime = assembleRuntime(bundle);
type Result =
  | { ok: true; stack: Value[]; steps: number; elapsedMs: number }
  | { ok: false; error: { code: string; message: string } };
const code = (r: Result) => (r.ok ? "ok" : r.error.code);
const msg = (r: Result) => (r.ok ? "" : r.error.message);
const top = (r: Result): Value => {
  if (!r.ok) throw new Error(`${r.error.code}: ${r.error.message}`);
  return r.stack[r.stack.length - 1] as Value;
};
const textOf = (r: Result): string => (top(r) as { v: string }).v;
const hex = (s: string) => Uint8Array.from((s.match(/../g) ?? []).map((x) => parseInt(x, 16)));
const enc = (s: string) => new TextEncoder().encode(s);

function toJson(v: Value): unknown {
  switch (v.tag) {
    case "list":
      return v.v.map(toJson);
    case "record":
      return Object.fromEntries([...v.v].map(([k, x]) => [k, toJson(x)]));
    case "int":
      return Number(v.v);
    case "str":
    case "bool":
      return v.v;
    default:
      throw new Error(`unexpected ${v.tag}`);
  }
}

// the engine primitive is private to the vocabulary: it is called directly, with the default limits
const engine = primitives[0] as PrimitiveDef;
const scan = async (rules: string, data: Uint8Array, matches = true): Promise<Result> => {
  const t0 = Date.now();
  try {
    const v = engine.fn(data, rules, matches, {
      limits: { maxValueBytes: 64 * 1024 * 1024 },
    }) as Value[];
    return { ok: true, stack: [{ tag: "list", v } as Value], steps: 0, elapsedMs: Date.now() - t0 };
  } catch (e) {
    const err = e as { code?: string; message: string };
    return { ok: false, error: { code: err.code ?? "?", message: err.message } };
  }
};
const op = async (
  rules: string,
  data: Uint8Array | string,
  flags: [boolean, boolean, boolean, boolean] = [false, false, false, false],
  limits?: { maxValueBytes?: number },
): Promise<Result> =>
  (await runtime.call(
    "yara:scan",
    [bytes(typeof data === "string" ? enc(data) : data), str(rules), ...flags.map(bool)],
    limits === undefined ? undefined : { limits },
  )) as Result;

interface Case {
  name: string;
  rules: string;
  data: string;
  expect: {
    name: string;
    tags: string[];
    meta: Record<string, string | number | boolean>;
    strings: Record<string, [number, number][]>;
  }[];
}

// Hex strings with alternatives of different lengths that start the same way: libyara reports the
// shorter path in some of them and the first choice in others (it depends on how it picks atoms), Forge
// always takes the first choice that lets the rest of the string match (leftmost-first, like a backtracking
// matcher), with lazy jumps. These cases are checked below against that rule, not against libyara.
const DIFFERENT_FROM_LIBYARA = new Set([
  "hex alt shortest",
  "random hex 28",
  "random hex 136",
  "random hex 139",
  "random hex 2",
  "random hex 31",
  "random hex 33",
  "random hex 93",
]);

describe("against libyara (yara-python 4.5.4)", () => {
  test("the fixture is large and varied", () => {
    expect((fixtures as Case[]).length).toBeGreaterThan(350);
  });
  for (const c of (fixtures as Case[]).filter((x) => !DIFFERENT_FROM_LIBYARA.has(x.name))) {
    test(c.name, async () => {
      const r = await scan(c.rules, hex(c.data));
      const got = toJson(top(r)) as {
        name: string;
        tags: string[];
        meta: { key: string; value: string; kind: string }[];
        strings: { id: string; count: number; matches: { offset: number; length: number }[] }[];
      }[];
      expect(got.map((g) => g.name)).toEqual(c.expect.map((e) => e.name));
      got.forEach((g, i) => {
        const e = c.expect[i] as Case["expect"][number];
        expect(g.tags).toEqual(e.tags);
        const meta = Object.fromEntries(
          g.meta.map((m) => [
            m.key,
            m.kind === "int" ? Number(m.value) : m.kind === "bool" ? m.value === "true" : m.value,
          ]),
        );
        expect(meta).toEqual(e.meta);
        const strings: Record<string, [number, number][]> = {};
        for (const s of g.strings) {
          strings[s.id] = s.matches.map((m) => [m.offset, m.length]);
          expect(s.count).toBe(s.matches.length);
        }
        expect(strings).toEqual(e.strings);
      });
    });
  }
});

describe("hex alternatives are leftmost-first", () => {
  const offs = async (hexs: string, data: string) => {
    const r = await scan(`rule a { strings: $a = { ${hexs} } condition: $a }`, enc(data));
    const g = toJson(top(r)) as { strings: { matches: { offset: number; length: number }[] }[] }[];
    return (g[0]?.strings[0]?.matches ?? []).map((m) => [m.offset, m.length]);
  };
  test("the first choice that lets the rest match wins", async () => {
    expect(await offs("61 ( 62 63 | 62 )", "abc")).toEqual([[0, 3]]);
    expect(await offs("61 ( 62 | 62 63 )", "abc")).toEqual([[0, 2]]);
    expect(await offs("61 ( 62 63 | 62 ) 64", "abd")).toEqual([[0, 3]]);
    expect(await offs("61 ( 62 63 | 62 ) 65", "abd")).toEqual([]);
    expect(await offs("61 ( 62 63 | 62 ) 63", "abc")).toEqual([[0, 3]]);
  });
  test("jumps are lazy", async () => {
    expect(await offs("61 [1-5] 62", "a..b..b")).toEqual([[0, 4]]);
    expect(await offs("61 [-] 62", "a..b..b")).toEqual([[0, 4]]);
    expect(await offs("61 [4-] 62", "a..b..b")).toEqual([[0, 7]]);
  });
});

