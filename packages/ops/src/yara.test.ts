describe("cost", () => {
  const dozens = Array.from({ length: 36 }, (_, i) => {
    const k = i % 6;
    const lit = `"needle${i}"`;
    if (k === 0) return `$s${i} = ${lit}`;
    if (k === 1) return `$s${i} = ${lit} nocase`;
    if (k === 2) return `$s${i} = ${lit} wide ascii`;
    if (k === 3) return `$s${i} = ${lit} xor`;
    if (k === 4) return `$s${i} = { 6E 65 65 64 ?? 65 ( 30 | 31 ) [0-2] 7A }`;
    return `$s${i} = /nee+d[a-z]*${i}/`;
  });
  const rules = `rule many { strings: ${dozens.join(" ")} condition: 1 of them or filesize > 0 }`;
  const data = new Uint8Array(65_536);
  let x = 12345;
  for (let i = 0; i < data.length; i++) {
    x = (x * 1103515245 + 12345) & 0x7fffffff;
    data[i] = 97 + (x % 26);
  }
  for (let i = 0; i < data.length - 20; i += 2000) data.set(enc(`needle${i % 36}`), i);

  test("64 KiB against 36 strings of every kind", async () => {
    const t0 = Date.now();
    const r = await scan(rules, data, false);
    const ms = Date.now() - t0;
    expect(code(r)).toBe("ok");
    expect(ms).toBeLessThan(5_000);
    console.log(`yara 64 KiB x 36 strings: ${ms} ms, ${r.ok ? r.steps : "?"} VM steps`);
  }, 60_000);

  test("the op over 64 KiB with strings shown", async () => {
    const r = await op(rules, data, [true, true, true, true]);
    expect(code(r)).toBe("ok");
    expect(r.ok && r.steps).toBeLessThan(20_000);
    console.log(
      `yara:scan 64 KiB all options: ${r.ok ? r.steps : "?"} VM steps, ${r.ok ? r.elapsedMs : "?"} ms`,
    );
  }, 60_000);

  test("65,536 matches of one string and the report", async () => {
    const r = await op("rule a { strings: $a = { 00 } condition: $a }", new Uint8Array(65_536), [
      true,
      true,
      false,
      true,
    ]);
    expect(code(r)).toBe("ok");
    expect(r.ok && r.steps).toBeLessThan(5_000_000);
    console.log(
      `yara:scan 65,536 matches reported: ${r.ok ? r.steps : "?"} VM steps, ${r.ok ? r.elapsedMs : "?"} ms`,
    );
  }, 60_000);
});

