describe("limits", () => {
  test("more than 100,000 matches of one string is E_LIMIT_VALUE", async () => {
    const r = await scan(
      'rule a { strings: $a = "a" condition: $a }',
      new Uint8Array(100_001).fill(97),
    );
    expect(code(r)).toBe("E_LIMIT_VALUE");
    expect(msg(r)).toMatch(/matches of one YARA string/);
    const ok = await scan(
      'rule a { condition: #a > 0 strings: $a = "a" }',
      new Uint8Array(1000).fill(97),
    );
    expect(code(ok)).toBe("E_COERCE"); // meta, strings, condition must come in that order
    const ok2 = await scan(
      'rule a { strings: $a = "a" condition: #a == 100000 }',
      new Uint8Array(100_000).fill(97),
      false,
    );
    expect(code(ok2)).toBe("ok");
    expect((toJson(top(ok2)) as unknown[]).length).toBe(1);
  });

  test("regex matches over the cap are E_LIMIT_VALUE", async () => {
    const r = await scan(
      "rule a { strings: $a = /a/ condition: $a }",
      new Uint8Array(100_001).fill(97),
    );
    expect(code(r)).toBe("E_LIMIT_VALUE");
  });

  test("input over 4 MiB is E_LIMIT_VALUE", async () => {
    const r = await scan('rule a { strings: $a = "a" condition: $a }', new Uint8Array(4_194_305));
    expect(code(r)).toBe("E_LIMIT_VALUE");
    expect(msg(r)).toMatch(/YARA input/);
  });

  test("an unbounded jump over 64 KiB runs into the work limit, not forever", async () => {
    const data = new Uint8Array(65_536); // zeros: every start offset walks to the end
    const t0 = Date.now();
    const r = await scan("rule a { strings: $a = { 00 [-] 01 } condition: $a }", data, false);
    expect(code(r)).toBe("E_LIMIT_VALUE");
    expect(msg(r)).toMatch(/work/);
    expect(Date.now() - t0).toBeLessThan(20_000);
  }, 60_000);

  test("a huge loop range is E_LIMIT_VALUE", async () => {
    const r = await scan(
      'rule a { strings: $a = "a" condition: $a and for all i in (1..1000000000) : (i > 0) }',
      enc("a"),
    );
    expect(code(r)).toBe("E_LIMIT_VALUE");
    const r2 = await scan(
      'rule a { strings: $a = "a" condition: $a and for all i in (1..3000) : (for all j in (1..3000) : (j > 0)) }',
      enc("a"),
    );
    expect(code(r2)).toBe("E_LIMIT_VALUE");
  }, 60_000);

  test("a result over the value limit is E_LIMIT_VALUE", async () => {
    const r = await op(
      'rule a { strings: $a = "a" condition: $a }',
      new Uint8Array(5000).fill(97),
      [true, false, false, false],
      {
        maxValueBytes: 100_000,
      },
    );
    expect(code(r)).toBe("E_LIMIT_VALUE");
  });
});

