/** The tables whose numbers can be GREASE values (RFC 8701). */
const GREASE_TABLES = new Set([
  "tls-version",
  "tls-extension",
  "tls-group",
  "tls-signature",
  "tls-cipher",
]);

export const NAME_TABLES: readonly string[] = Object.freeze(Object.keys(SOURCES));

const maps = new Map<string, ReadonlyMap<number, string>>();

function mapOf(table: string): ReadonlyMap<number, string> | undefined {
  const cached = maps.get(table);
  if (cached) return cached;
  const src = SOURCES[table];
  if (!src) return undefined;
  const m = new Map<number, string>(src);
  maps.set(table, m);
  return m;
}

/** A GREASE value: both bytes the same, and the low nibble of each A (0x0a0a, 0x1a1a, ... 0xfafa). */
export function isGrease(n: number): boolean {
  return n >= 0 && n <= 0xffff && (n & 0xff) === n >> 8 && (n & 0x0f) === 0x0a;
}

/** The name of a number in a table, the empty string when it has none, undefined for an unknown table. */
export function nameOf(table: string, key: number): string | undefined {
  const m = mapOf(table);
  if (!m) return undefined;
  return m.get(key) ?? (GREASE_TABLES.has(table) && isGrease(key) ? "GREASE" : "");
}

/** The number of entries of a table (for the tests). */
export function tableSize(table: string): number {
  return mapOf(table)?.size ?? 0;
}
