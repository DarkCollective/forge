/*
 * The name tables of the `packets` vocabulary: EtherTypes, IP protocol numbers, IPv4 and TCP option kinds,
 * and the TLS registries (record content types, versions, handshake types, alert descriptions, cipher
 * suites, extensions, supported groups, signature schemes, EC point formats, compression methods,
 * certificate compression algorithms, PSK key exchange modes). The data for the `packets:_name`
 * primitive (src/prims/packets.ts); it lives here, not in prims/, because every file in prims/ is loaded
 * as a vocabulary's primitive module.
 *
 * Why a table in TypeScript and not in FL: FL has no per-vocabulary constants, so an FL table is rebuilt on
 * every call (the asn1 OID table measured about 1,800 VM steps for 200 pairs); the primitive builds each
 * map once and a lookup is 2 VM steps.
 *
 * Sources (the names are the IANA registry names, as the RFCs and OpenSSL's `-stdname` print them):
 *  - cipher suites: the 326 suites of the HTTP/2 block list of Go's net/http (which is RFC 7540 appendix A,
 *    taken from the IANA registry), compared with the names of OpenSSL 3.0.13's `openssl ciphers -stdname
 *    -V` and of its <openssl/tls1.h> (no name differs), plus the five TLS 1.3 suites of RFC 8446 and RFC 8447
 *    (0x1301 to 0x1305) and the four ECDHE_PSK suites of RFC 8442 (0xD001, 0xD002, 0xD003, 0xD005), which
 *    the first two lack. The RFC 8442 four are from the RFC, not checked against a tool here.
 *  - everything else: the IANA registries as published by RFC 8446 (extensions, groups, signature schemes),
 *    RFC 8422, RFC 7919, RFC 7301, RFC 8879, RFC 9001 and the IANA assignments of the other numbers.
 * A number that is not in a table has no name (the empty string); GREASE values (RFC 8701, 0x0a0a, 0x1a1a,
 * ... 0xfafa) are named GREASE in the tables that RFC covers.
 */

